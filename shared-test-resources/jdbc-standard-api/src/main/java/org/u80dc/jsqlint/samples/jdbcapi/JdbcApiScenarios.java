package org.u80dc.jsqlint.samples.jdbcapi;

import java.sql.*;

/** 为尚未进入共享项目的标准签名提供可调用、固定输入的真实目标方法。 */
public final class JdbcApiScenarios {
    public static void createTables(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE jdbc_api (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80))");
            statement.execute("CREATE TABLE jdbc_state (case_name VARCHAR(80), row_value INTEGER)");
            statement.execute("CREATE TABLE jdbc_generated (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(80))");
        }
    }

    public static int createStatementHoldability(Connection connection) throws SQLException {
        try (var statement = connection.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY,
                ResultSet.HOLD_CURSORS_OVER_COMMIT); var rows = statement.executeQuery("SELECT 101")) {
            rows.next();
            return rows.getInt(1);
        }
    }

    public static int scrollingPrepared(Connection connection) throws SQLException {
        try (var statement = connection.prepareStatement("SELECT ? /* scroll prepared */", ResultSet.TYPE_SCROLL_INSENSITIVE,
                ResultSet.CONCUR_READ_ONLY)) {
            statement.setInt(1, 11);
            try (var rows = statement.executeQuery()) {
                rows.next();
                return rows.getInt(1);
            }
        }
    }

    public static int plainCallable(Connection connection) throws SQLException {
        try (var statement = connection.prepareCall("{? = call ABS(?)} /* plain callable */")) {
            statement.registerOutParameter(1, Types.INTEGER);
            statement.setInt(2, -12);
            statement.execute();
            return statement.getInt(1);
        }
    }

    public static int holdableCallable(Connection connection) throws SQLException {
        try (var statement = connection.prepareCall("{? = call ABS(?)} /* holdable callable */", ResultSet.TYPE_FORWARD_ONLY,
                ResultSet.CONCUR_READ_ONLY, ResultSet.HOLD_CURSORS_OVER_COMMIT)) {
            statement.registerOutParameter(1, Types.INTEGER);
            statement.setInt(2, -13);
            statement.execute();
            return statement.getInt(1);
        }
    }

    /** 返回值由驱动翻译；SQL 提取入口的基准是传入 nativeSQL 的原始文本。 */
    public static String nativeSql(Connection connection) throws SQLException {
        return connection.nativeSQL("SELECT {fn ABS(-14)}");
    }

    public static long executeGeneratedFlag(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            statement.execute("INSERT INTO jdbc_api (name) VALUES ('execute flag')", Statement.RETURN_GENERATED_KEYS);
            try (var rows = statement.getGeneratedKeys()) {
                rows.next();
                return rows.getLong(1);
            }
        }
    }

    public static long executeGeneratedIndexes(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            statement.execute("INSERT INTO jdbc_api (name) VALUES ('execute indexes')", new int[]{1});
            try (var rows = statement.getGeneratedKeys()) {
                rows.next();
                return rows.getLong(1);
            }
        }
    }

    public static long executeGeneratedNames(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            statement.execute("INSERT INTO jdbc_api (name) VALUES ('execute names')", new String[]{"ID"});
            try (var rows = statement.getGeneratedKeys()) {
                rows.next();
                return rows.getLong(1);
            }
        }
    }

    public static int updateGeneratedFlag(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeUpdate("INSERT INTO jdbc_api (name) VALUES ('update flag')", Statement.RETURN_GENERATED_KEYS);
        }
    }

    public static int updateGeneratedIndexes(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeUpdate("INSERT INTO jdbc_api (name) VALUES ('update indexes')", new int[]{1});
        }
    }

    public static int updateGeneratedNames(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeUpdate("INSERT INTO jdbc_api (name) VALUES ('update names')", new String[]{"ID"});
        }
    }

    public static long largeUpdatePlain(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeLargeUpdate("INSERT INTO jdbc_api (name) VALUES ('large plain')");
        }
    }

    public static long largeUpdateGeneratedFlag(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeLargeUpdate("INSERT INTO jdbc_api (name) VALUES ('large flag')", Statement.RETURN_GENERATED_KEYS);
        }
    }

    public static long largeUpdateGeneratedIndexes(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeLargeUpdate("INSERT INTO jdbc_api (name) VALUES ('large indexes')", new int[]{1});
        }
    }

    public static long largeUpdateGeneratedNames(Connection connection) throws SQLException {
        try (var statement = connection.createStatement()) {
            return statement.executeLargeUpdate("INSERT INTO jdbc_api (name) VALUES ('large names')", new String[]{"ID"});
        }
    }

    public static ResultSet numericBindings(Connection connection) throws SQLException {
        var statement = connection.prepareStatement("SELECT ?, ?, ?, ?, ?, ?, ?, ? /* numeric bindings */");
        statement.closeOnCompletion();
        statement.setByte(1, (byte) 7);
        statement.setShort(2, (short) 32000);
        statement.setLong(3, 9_000_000_000L);
        statement.setFloat(4, 1.25f);
        statement.setDouble(5, 2.5d);
        statement.setObject(6, "plain object");
        statement.setObject(7, 42, Types.INTEGER, 0);
        statement.setNull(8, Types.VARCHAR, "VARCHAR");
        return statement.executeQuery();
    }

    /** 下标从项目辅助方法计算，实际仍确定为位置 2，不是外部未知下标。 */
    public static ResultSet dynamicIndex(Connection connection) throws SQLException {
        var statement = connection.prepareStatement("SELECT ?, ? /* dynamic index */");
        statement.closeOnCompletion();
        statement.setInt(1, 77);
        statement.setInt(nextIndex(1), 88);
        return statement.executeQuery();
    }

    private static int nextIndex(int previous) {
        return previous + 1;
    }

    /** H2 不实现这些存储过程/命名绑定；必须由兼容驱动或 JDBC 接口记录器独立执行。 */
    public static int namedCallable(Connection connection) throws SQLException {
        try (var statement = connection.prepareCall("{call JDBC_NAMED(?, ?, ?, ?, ?)}")) {
            statement.setString("name", "Ada");
            statement.setInt("number", 42);
            statement.setNull("optional", Types.VARCHAR);
            statement.setObject("object", "named object", JDBCType.VARCHAR);
            statement.registerOutParameter("output", Types.INTEGER);
            statement.execute();
            return statement.getInt("output");
        }
    }

    /** INOUT 位置 1 同时声明输入/输出；位置 2、3 只声明输出，不创建输入绑定。 */
    public static void inOutCallable(Connection connection) throws SQLException {
        try (var statement = connection.prepareCall("{call JDBC_INOUT(?, ?, ?)}")) {
            statement.setInt(1, 7);
            statement.registerOutParameter(1, Types.INTEGER);
            statement.registerOutParameter(2, Types.VARCHAR);
            statement.registerOutParameter(3, Types.BIGINT);
            statement.execute();
        }
    }

    public static int countRows(Connection connection) throws SQLException {
        try (var statement = connection.createStatement(); var rows = statement.executeQuery("SELECT COUNT(*) FROM jdbc_api")) {
            rows.next();
            return rows.getInt(1);
        }
    }
}
